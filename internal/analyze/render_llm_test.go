func TestRenderLLM_SyntheticPureNoArchive(t *testing.T) {
	longExcerpt := strings.Repeat("x", 400)
	rep := Report{
		RunID:         "run-synth-001",
		ArchiveSHA256: "deadbeef",
		Summary:       "1 hint (CrashLoopBackOff)",
		Hints: []Hint{{
			Kind:     KindCrashLoopBackOff,
			Severity: SeverityError,
			Title:    "CrashLoopBackOff for demo/nginx",
			Summary:  "Pod may be crash-looping based on events",
			Evidence: []Evidence{{
				Path:    "extras/all-cluster-events.log",
				Excerpt: longExcerpt,
			}},
		}},
		Notes: []Note{{
			Code:    "member_missing",
			Message: "optional member not found",
			Path:    "extras/all-pods-wide.txt",
		}},
	}

	md, err := RenderLLM(rep)
	if err != nil {
		t.Fatalf("RenderLLM: %v", err)
	}
	for _, want := range []string{
		"## Instructions for the assistant",
		"hint or hypothesis",
		"run-synth-001",
		"deadbeef",
		"CrashLoopBackOff",
		"extras/all-cluster-events.log",
		"## Secrets warning",
		"unredacted archive text",
		"`.log`",
		"generated by groot analyze --output llm",
	} {
		if !strings.Contains(md, want) {
			t.Fatalf("markdown missing %q:\n%s", want, md)
		}
	}
	if strings.Contains(strings.ToLower(md), "root cause is") {
		t.Fatalf("must not claim definitive root cause:\n%s", md)
	}
	if !strings.Contains(md, "**not** claimed ChatGPT-safe") {
		t.Fatalf("secrets warning must deny ChatGPT-safe claim:\n%s", md)
	}

	// Excerpt clipped at render time to llmExcerptMaxRunes (+ ellipsis).
	excerpt := extractFencedExcerpt(md)
	if n := utf8.RuneCountInString(strings.TrimSuffix(excerpt, "…")); n > llmExcerptMaxRunes {
		t.Fatalf("excerpt runes = %d, want <= %d (%q)", n, llmExcerptMaxRunes, excerpt)
	}
	// Caller Report must be unchanged.
	if utf8.RuneCountInString(rep.Hints[0].Evidence[0].Excerpt) != 400 {
		t.Fatalf("RenderLLM mutated caller Report excerpt")
	}
	if len(md) > DefaultLLMBudgetBytes {
		t.Fatalf("len(md)=%d > DefaultLLMBudgetBytes", len(md))
	}
}

func TestRenderLLM_CrashLoopGolden(t *testing.T) {
	rep := runFixtureReport(t, "crashloop")
	// Temp pack paths are not golden-stable; identity is covered by run_id/sha.
	rep.ArchivePath = ""
	md, err := RenderLLM(rep)
	if err != nil {
		t.Fatalf("RenderLLM: %v", err)
	}
	for _, want := range []string{
		"## Instructions for the assistant",
		"run-crashloop-001",
		"abc123deadbeef0123456789abcdef",
		"CrashLoopBackOff",
		"## Secrets warning",
		"unredacted",
		"generated by groot analyze --output llm",
	} {
		if !strings.Contains(md, want) {
			t.Fatalf("missing %q:\n%s", want, md)
		}
	}
	lower := strings.ToLower(md)
	if strings.Contains(lower, "root cause is") || strings.Contains(lower, "diagnosed as") {
		t.Fatalf("definitive diagnosis language forbidden:\n%s", md)
	}

	goldenPath := filepath.Join("testdata", "llm_crashloop.golden.md")
	if os.Getenv("UPDATE_GOLDEN") == "1" {
		if err := os.WriteFile(goldenPath, []byte(md), 0o644); err != nil {
			t.Fatalf("write golden: %v", err)
		}
	}
	want, err := os.ReadFile(goldenPath)
	if err != nil {
		t.Fatalf("read golden (run UPDATE_GOLDEN=1): %v", err)
	}
	if diff := cmp.Diff(string(want), md); diff != "" {
		t.Fatalf("golden mismatch (-want +got):\n%s", diff)
	}
}

