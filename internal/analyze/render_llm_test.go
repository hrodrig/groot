func TestRenderLLM_TinyBudgetOmitMarker(t *testing.T) {
	// One retained hint with a huge summary forces head/tail after excerpt shrink.
	rep := Report{
		RunID:         "run-omit",
		ArchiveSHA256: "omitsha",
		Summary:       "omit stress",
		Hints: []Hint{{
			Kind:     KindCrashLoopBackOff,
			Severity: SeverityError,
			Title:    "huge hint " + strings.Repeat("T", 200),
			Summary:  strings.Repeat("SUMMARY-LINE\n", 400),
			Evidence: []Evidence{{
				Path:    "extras/all-cluster-events.log",
				Excerpt: strings.Repeat("E", 400),
			}},
			OpenQuestions: []string{strings.Repeat("Q", 300)},
		}},
	}
	budget := 2800
	md, err := renderLLM(rep, budget)
	if err != nil {
		t.Fatalf("renderLLM: %v", err)
	}
	if len(md) > budget {
		t.Fatalf("len=%d > budget=%d", len(md), budget)
	}
	if !strings.Contains(md, "[omitted") || !strings.Contains(md, "bytes]") {
		t.Fatalf("expected visible omit marker, got:\n%s", md)
	}
	if !strings.Contains(md, "… [omitted") {
		t.Fatalf("omit marker must use locked ellipsis form:\n%s", md)
	}
	for _, want := range []string{
		"## Instructions for the assistant",
		"## Secrets warning",
		"unredacted archive text",
		"generated by groot analyze --output llm",
	} {
		if !strings.Contains(md, want) {
			t.Fatalf("must keep framing/warning/footer (%q missing):\n%s", want, md)
		}
	}
}

