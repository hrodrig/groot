const llmSuffixTmpl = `## Secrets warning

This paste may still contain **unredacted archive text**. Collect-time redaction covers ` + "`.log`" + ` members only; excerpts may include data from events, TSV, or resources. Do not paste into untrusted systems if the archive may hold credentials or PII. This packet is **not** claimed ChatGPT-safe or scrubbed for external chat vendors.

---
generated by groot analyze --output llm
`

var (
	llmPrefixTemplate = template.Must(
		template.New("llm-prefix").
			Option("missingkey=error").
			Parse(llmPrefixTmpl),
	)
	llmFindingsTemplate = template.Must(
		template.New("llm-findings").
			Option("missingkey=error").
			Funcs(template.FuncMap{
				"add": func(a, b int) int { return a + b },
			}).
			Parse(llmFindingsTmpl),
	)
	llmSuffixTemplate = template.Must(
		template.New("llm-suffix").
			Option("missingkey=error").
			Parse(llmSuffixTmpl),
	)
)

// RenderLLM renders Report as LLM-ready Markdown (LLM-01..03).
// Pure: does not open archives or re-run heuristics.
// Successful output length is always <= DefaultLLMBudgetBytes (UTF-8 bytes).
func RenderLLM(r Report) (string, error) {
	return renderLLM(r, DefaultLLMBudgetBytes)
}

// renderLLM is the budget-parameterized implementation (tests force omit markers).
func renderLLM(r Report, budget int) (string, error) {
	if budget <= 0 {
		return "", fmt.Errorf("llm budget must be positive, got %d", budget)
	}
	vm := buildLLMView(r)

	for {
		out, err := assembleLLM(vm, "")
		if err != nil {
			return "", err
		}
		if len(out) <= budget {
			return out, nil
		}
		if !shrinkLLMView(&vm) {
			break
		}
	}

	prefix, findings, suffix, err := renderLLMParts(vm)
	if err != nil {
		return "", err
	}
	framing := len(prefix) + len(suffix)
	if framing > budget {
		return "", fmt.Errorf("llm framing exceeds budget (%d bytes > %d)", framing, budget)
	}
	avail := budget - framing
	findings = headTailOmit(findings, avail)
	return normalizeLLM(prefix + findings + suffix), nil
}

func buildLLMView(r Report) llmView {
	vm := llmView{
		RunID:                r.RunID,
		ArchiveSHA256:        r.ArchiveSHA256,
		ArchiveLayoutVersion: r.ArchiveLayoutVersion,
		ArchivePath:          r.ArchivePath,
		Summary:              r.Summary,
	}
	for _, h := range r.Hints {
		hv := llmHintView{
			Kind:          string(h.Kind),
			Severity:      h.Severity.String(),
			Title:         h.Title,
			Summary:       h.Summary,
			OpenQuestions: append([]string(nil), h.OpenQuestions...),
		}
		for _, e := range h.Evidence {
			hv.Evidence = append(hv.Evidence, llmEvidenceView{
				Path:    e.Path,
				Excerpt: clipRunes(e.Excerpt, llmExcerptMaxRunes),
			})
		}
		vm.Hints = append(vm.Hints, hv)
	}
	for _, n := range r.Notes {
		vm.Notes = append(vm.Notes, llmNoteView{
			Code:    n.Code,
			Message: n.Message,
			Path:    n.Path,
		})
	}
	return vm
}

func clipRunes(s string, max int) string {
	if max <= 0 || s == "" {
		return ""
	}
	r := []rune(s)
	if len(r) <= max {
		return s
	}
	return string(r[:max]) + "…"
}

// shrinkLLMView drops lowest-value content. Returns false when nothing left to
// drop via the view-model — caller then head/tail-omits the findings body.
// Keeps at least one hint when present so forced truncation can surface omit
// markers instead of silently emptying the findings section.
func shrinkLLMView(vm *llmView) bool {
	// 1) Clear excerpts from the trailing hint first.
	for i := len(vm.Hints) - 1; i >= 0; i-- {
		for j := len(vm.Hints[i].Evidence) - 1; j >= 0; j-- {
			if vm.Hints[i].Evidence[j].Excerpt != "" {
				vm.Hints[i].Evidence[j].Excerpt = ""
				return true
			}
		}
	}
	// 2) Trim note messages (keep codes/paths).
	for i := len(vm.Notes) - 1; i >= 0; i-- {
		if vm.Notes[i].Message != "" {
			vm.Notes[i].Message = ""
			return true
		}
	}
	// 3) Drop trailing notes once messages are empty.
	if len(vm.Notes) > 0 {
		vm.Notes = vm.Notes[:len(vm.Notes)-1]
		return true
	}
	// 4) Drop trailing hints but keep the highest-priority (first) hint for
	//    last-resort head/tail omit of the findings body.
	if len(vm.Hints) > 1 {
		vm.Hints = vm.Hints[:len(vm.Hints)-1]
		return true
	}
	// 5) Truncate summary as last view-model shrink before head/tail.
	if vm.Summary != "" {
		r := []rune(vm.Summary)
		if len(r) > 80 {
			vm.Summary = string(r[:80]) + "…"
			return true
		}
		if len(r) > 0 {
			vm.Summary = ""
			return true
		}
	}
	return false
}

func assembleLLM(vm llmView, findingsOverride string) (string, error) {
	prefix, findings, suffix, err := renderLLMParts(vm)
	if err != nil {
		return "", err
	}
	if findingsOverride != "" {
		findings = findingsOverride
	}
	return normalizeLLM(prefix + findings + suffix), nil
}

func renderLLMParts(vm llmView) (prefix, findings, suffix string, err error) {
	var pbuf, fbuf, sbuf bytes.Buffer
	if err = llmPrefixTemplate.Execute(&pbuf, vm); err != nil {
		return "", "", "", fmt.Errorf("render llm prefix: %w", err)
	}
	if err = llmFindingsTemplate.Execute(&fbuf, vm); err != nil {
		return "", "", "", fmt.Errorf("render llm findings: %w", err)
	}
	if err = llmSuffixTemplate.Execute(&sbuf, vm); err != nil {
		return "", "", "", fmt.Errorf("render llm suffix: %w", err)
	}
	return pbuf.String(), fbuf.String(), sbuf.String(), nil
}

func normalizeLLM(out string) string {
	return strings.TrimRight(out, " \t") + "\n"
}

// headTailOmit keeps a head and tail of s under maxBytes, inserting a visible
// omit marker. N in the marker is len(original)-len(head)-len(tail): UTF-8
// bytes removed from the middle (not counting the marker itself).
func headTailOmit(s string, maxBytes int) string {
	if maxBytes <= 0 {
		return ""
	}
	if len(s) <= maxBytes {
		return s
	}

	// Reserve space using the widest plausible marker (N = len(s)).
	probe := fmt.Sprintf(llmOmitMarkerFmt, len(s))
	remain := maxBytes - len(probe)
	if remain < 0 {
		marker := fmt.Sprintf(llmOmitMarkerFmt, len(s))
		if len(marker) <= maxBytes {
			return marker
		}
		return cutPrefixBytes(marker, maxBytes)
	}

	headBudget := remain * 60 / 100
	tailBudget := remain - headBudget
	head := cutPrefixBytes(s, headBudget)
	tail := cutSuffixBytes(s, tailBudget)
	head = snapHeadNewline(head, headBudget)
	tail = snapTailNewline(tail, tailBudget)

	// Ensure a non-empty omitted middle when head+tail would cover the whole string.
	for len(head)+len(tail) >= len(s) && (len(head) > 0 || len(tail) > 0) {
		if len(head) >= len(tail) && len(head) > 0 {
			_, size := utf8.DecodeLastRuneInString(head)
			head = head[:len(head)-size]
		} else if len(tail) > 0 {
			_, size := utf8.DecodeRuneInString(tail)
			tail = tail[size:]
		}
	}

	omitted := len(s) - len(head) - len(tail)
	if omitted < 1 {
		omitted = len(s)
		head, tail = "", ""
	}
	marker := fmt.Sprintf(llmOmitMarkerFmt, omitted)
	out := head + marker + tail
	if len(out) <= maxBytes {
		return out
	}
	// Marker shrank vs probe — spend leftover on head; still enforce ceiling.
	extra := maxBytes - len(out)
	if extra > 0 {
		head = cutPrefixBytes(s, len(head)+extra)
		for len(head)+len(tail) >= len(s) && len(head) > 0 {
			_, size := utf8.DecodeLastRuneInString(head)
			head = head[:len(head)-size]
		}
		omitted = len(s) - len(head) - len(tail)
		marker = fmt.Sprintf(llmOmitMarkerFmt, omitted)
		out = head + marker + tail
		if len(out) <= maxBytes {
			return out
		}
	}
	if len(marker) <= maxBytes {
		return marker
	}
	return cutPrefixBytes(s, maxBytes)
}

func cutPrefixBytes(s string, maxBytes int) string {
	if maxBytes <= 0 || s == "" {
		return ""
	}
	if len(s) <= maxBytes {
		return s
	}
	// Walk runes until adding another would exceed maxBytes.
	n := 0
	for n < len(s) {
		_, size := utf8.DecodeRuneInString(s[n:])
		if n+size > maxBytes {
			break
		}
		n += size
	}
	return s[:n]
}

func cutSuffixBytes(s string, maxBytes int) string {
	if maxBytes <= 0 || s == "" {
		return ""
	}
	if len(s) <= maxBytes {
		return s
	}
	start := len(s)
	used := 0
	for start > 0 {
		r, size := utf8.DecodeLastRuneInString(s[:start])
		if r == utf8.RuneError && size == 1 {
			size = 1
		}
		if used+size > maxBytes {
			break
		}
		start -= size
		used += size
	}
	return s[start:]
}

func snapHeadNewline(head string, budget int) string {
	if head == "" {
		return head
	}
	window := budget / 5
	if window < 8 {
		window = 8
	}
	from := len(head) - window
	if from < 0 {
		from = 0
	}
	if idx := strings.LastIndex(head[from:], "\n"); idx >= 0 {
		return head[:from+idx+1]
	}
	return head
}

func snapTailNewline(tail string, budget int) string {
	if tail == "" {
		return tail
	}
	window := budget / 5
	if window < 8 {
		window = 8
	}
	to := window
	if to > len(tail) {
		to = len(tail)
	}
	if idx := strings.Index(tail[:to], "\n"); idx >= 0 {
		return tail[idx+1:]
	}
	return tail
}
