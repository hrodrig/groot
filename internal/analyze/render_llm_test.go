func runFixtureReport(t *testing.T, name string) Report {
	t.Helper()
	src := filepath.Join("testdata", name)
	out := filepath.Join(t.TempDir(), name+".tar.gz")
	if err := archive.DirToTarGz(src, out); err != nil {
		t.Fatalf("DirToTarGz: %v", err)
	}
	arc, err := arcread.Open(out)
	if err != nil {
		t.Fatalf("Open: %v", err)
	}
	defer arc.Close()
	rep, err := Run(arc)
	if err != nil {
		t.Fatalf("Run: %v", err)
	}
	return rep
}

func fatReport(hints, excerptRunes int) Report {
	ex := strings.Repeat("Z", excerptRunes)
	rep := Report{
		RunID:         "run-fat",
		ArchiveSHA256: "fatsha",
		Summary:       "many hints",
	}
	for i := 0; i < hints; i++ {
		rep.Hints = append(rep.Hints, Hint{
			Kind:     KindCrashLoopBackOff,
			Severity: SeverityError,
			Title:    "hint " + strings.Repeat("T", 8) + " " + strings.Repeat("0", i%10),
			Summary:  "summary " + strings.Repeat("S", 40),
			Evidence: []Evidence{{
				Path:    "extras/all-cluster-events.log",
				Excerpt: ex,
			}},
		})
	}
	for i := 0; i < 5; i++ {
		rep.Notes = append(rep.Notes, Note{
			Code:    "note",
			Message: strings.Repeat("note-message-", 20),
			Path:    "extras/x.txt",
		})
	}
	return rep
}

func extractFencedExcerpt(md string) string {
	const fence = "```"
	i := strings.Index(md, fence)
	if i < 0 {
		return ""
	}
	rest := md[i+len(fence):]
	// skip optional language / blank
	if nl := strings.IndexByte(rest, '\n'); nl >= 0 {
		rest = rest[nl+1:]
	}
	j := strings.Index(rest, fence)
	if j < 0 {
		return strings.TrimSpace(rest)
	}
	return strings.TrimRight(rest[:j], "\n")
}
